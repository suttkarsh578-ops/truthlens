from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session
from app.schemas.prediction import PredictRequest, PredictResponse
from app.services.prediction_service import prediction_service
from app.database.session import get_db
from app.models.prediction import Prediction

router = APIRouter()

@router.post("", response_model=PredictResponse)
@router.post("/", response_model=PredictResponse)
def predict(request: PredictRequest, db: Session = Depends(get_db)):
    result = prediction_service.predict(request.headline or "", request.content or "")

    db_pred = Prediction(
        headline=request.headline,
        content=request.content,
        prediction=result.get("prediction"),
        confidence=result.get("confidence"),
        model_name=result.get("model_name"),
        processing_time_ms=result.get("processing_time_ms")
    )
    db.add(db_pred)
    db.commit()

    result["disclaimer"] = "Classification is generated by the trained machine-learning model and does not independently verify factual truth."
    return PredictResponse(**result)